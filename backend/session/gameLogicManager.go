package session

import (
	"fmt"
	"maps"
	"math/rand/v2"
	"slices"

	sessionv1 "github.com/TeamHermes-jhu/clueless/backend/internal/gen/session/v1"
	suggestionv1 "github.com/TeamHermes-jhu/clueless/backend/internal/gen/suggestion/v1"
)

const (
	// text formats for logging.
	suggestFmt = "player %s has suggested: %s with the %s in the %s"
	accuseFmt  = "player %s has made an accusation: %s with the %s in the %s"
	moveFmt    = "player %s has moved to %s"

	// number of each type of card in the game.
	numSuspects = 6
	numRooms    = 9
	numWeapons  = 6

	// card type numbers.
	cardSuspect = 1
	cardRoom    = 2
	cardWeapon  = 3

	// number of halls in the game.
	// numHalls = 12 will be used later.

	// text formats for game initialization.
	caseFileFmt       = "Spoiler alert! case file: suspect %d, room %d, weapon %d"
	playerHandFmt     = "player %s hand: suspects %v, rooms %v, weapons %v"
	playerLocationFmt = "player %s location: isHall %t, location %d"
)

// playerLocation represents the location of a player in the game, which can be a room or a hall.
type playerLocation struct {
	isHall   bool
	location int
}

// CaseFile represents the solution to the game, containing the suspect, room, and weapon cards.
type CaseFile struct {
	// the cardsv1 stuff generated by protobuf is a MESSAGE, not the struct itself.
	// We just store the int values of the cards in the case file.
	suspectCard int
	roomCard    int
	weaponCard  int
}

// PlayerHand represents the cards in a player's hand.
type PlayerHand struct {
	// can have multiple cards of the same type, so each is an array
	suspectCards []int
	roomCards    []int
	weaponCards  []int
}

// GameLogicManager manages the game logic for a session, including the case file, player hands, and player locations.
type GameLogicManager struct {
	// needs to be associated with a session (contains turn order, players, turnIdx)
	session *Session

	// needs to maintain a case file (suspect, room, weapon)
	caseFile CaseFile

	// needs to maintain all the players' hands
	hands map[string]*PlayerHand

	// needs to maintain the location of all the players
	locations map[string]*playerLocation
}

func (s *Session) startGame() {
	s.logger.Info("Starting game", "players", len(s.players))
	s.started = true

	s.broadcastMessage("game is starting")

	r := rand.Perm(len(s.players))

	s.turnOrder = make([]string, len(s.joinOrder))
	for i, v := range r {
		s.turnOrder[v] = s.joinOrder[i]
	}

	g := GameLogicManager{
		session:   s,
		caseFile:  CaseFile{},
		hands:     make(map[string]*PlayerHand),
		locations: make(map[string]*playerLocation),
	}

	playerIDs := slices.Collect(maps.Keys(s.players))

	g.setupGame(playerIDs)
}

func (s *Session) move(move *sessionv1.Move) {
	// TODO: validate its a good move
	to := move.GetRoom().String()

	if move.WhichMoveTo() == sessionv1.Move_Hall_case {
		to = move.GetRoom().String()
	}

	s.broadcastMessage(fmt.Sprintf(moveFmt, move.GetPlayerId(), to))
}

func (s *Session) suggest(suggestion *suggestionv1.SuggestionRequest) {
	// TODO: figure out how to handle suggestions
	s.broadcastMessage(fmt.Sprintf(
		suggestFmt,
		suggestion.GetPlayerId(),
		suggestion.GetCharacter().String(),
		suggestion.GetWeapon().String(),
		suggestion.GetRoom().String(),
	))
}

func (s *Session) accuse(accusation *suggestionv1.AccusationRequest) {
	// TODO: validation + logic
	s.broadcastMessage(fmt.Sprintf(
		accuseFmt,
		accusation.GetSuggestion().GetPlayerId(),
		accusation.GetSuggestion().GetCharacter().String(),
		accusation.GetSuggestion().GetWeapon().String(),
		accusation.GetSuggestion().GetRoom().String(),
	))
}

func (g *GameLogicManager) setupGame(playerIDs []string) {
	// set up the game logic for a new game
	// create the case file (suspect, room, weapon)
	// deal the cards to each player (shuffled)
	// put each player in their starting room
	g.setupCaseFile()
	g.initializeHands(playerIDs)
	g.dealCards(playerIDs)
	g.setupPlayerLocations(playerIDs)
}

func (g *GameLogicManager) setupCaseFile() {
	// create the case file (suspect, room, weapon)
	g.session.broadcastMessage("Setting up the case file...")

	//nolint:gosec // rand.IntN is used for selecting random cards, not for security-sensitive purposes.
	suspect := rand.IntN(numSuspects) + 1
	//nolint:gosec // rand.IntN is used for selecting random cards, not for security-sensitive purposes.
	room := rand.IntN(numRooms) + 1
	//nolint:gosec // rand.IntN is used for selecting random cards, not for security-sensitive purposes.
	weapon := rand.IntN(numWeapons) + 1

	g.caseFile = CaseFile{
		suspectCard: suspect,
		roomCard:    room,
		weaponCard:  weapon,
	}

	g.session.broadcastMessage(fmt.Sprintf(caseFileFmt, suspect, room, weapon))
}

func (g *GameLogicManager) initializeHands(playerIDs []string) {
	g.hands = make(map[string]*PlayerHand)
	for _, playerID := range playerIDs {
		g.hands[playerID] = &PlayerHand{}
	}
}

func (g *GameLogicManager) dealCards(playerIDs []string) {
	// we have 18 cards left, 5 suspects/weapons and 8 rooms
	g.session.broadcastMessage("Dealing cards to players...")

	allCards := make([]int, numSuspects+numRooms+numWeapons)
	for i := range allCards {
		allCards[i] = i + 1
	}

	allCards = removeCardFromDeck(allCards, g.caseFile.suspectCard, cardSuspect)
	allCards = removeCardFromDeck(allCards, g.caseFile.roomCard, cardRoom)
	allCards = removeCardFromDeck(allCards, g.caseFile.weaponCard, cardWeapon)
	// we want to deal them sequentially to players, uniformly randomly (all shuffled together)

	rand.Shuffle(len(allCards), func(i, j int) {
		allCards[i], allCards[j] = allCards[j], allCards[i]
	})

	currentplayerIDxToDeal := 1

	for len(allCards) > 0 {
		cardToDeal := allCards[0]
		allCards = allCards[1:]
		// assign the card to the current player
		switch {
		case cardToDeal <= numSuspects:
			// assign suspect card to current player
			g.hands[playerIDs[currentplayerIDxToDeal-1]].suspectCards = append(g.hands[playerIDs[currentplayerIDxToDeal-1]].suspectCards, cardToDeal)
		case cardToDeal <= numSuspects+numRooms:
			// assign room card to current player
			cardToDeal -= numSuspects
			g.hands[playerIDs[currentplayerIDxToDeal-1]].roomCards = append(g.hands[playerIDs[currentplayerIDxToDeal-1]].roomCards, cardToDeal)
		default:
			// assign weapon card to current player
			cardToDeal -= numSuspects + numRooms
			g.hands[playerIDs[currentplayerIDxToDeal-1]].weaponCards = append(g.hands[playerIDs[currentplayerIDxToDeal-1]].weaponCards, cardToDeal)
		}

		currentplayerIDxToDeal = (currentplayerIDxToDeal % len(playerIDs)) + 1
	}

	// broadcast the final hands to all players
	for _, playerID := range playerIDs {
		g.session.broadcastMessage(fmt.Sprintf(playerHandFmt, playerID, g.hands[playerID].suspectCards, g.hands[playerID].roomCards, g.hands[playerID].weaponCards))
	}
}

func removeCardFromDeck(deck []int, cardNum int, cardType int) []int {
	// cardType == 1 -> suspect
	// cardType == 2 -> room
	// cardType == 3 -> weapon
	switch cardType {
	case cardSuspect:
		// suspect cards are at the beginning of the deck
	case cardRoom:
		// room cards are after the suspect cards in the deck
		cardNum += numSuspects
	case cardWeapon:
		// weapon cards are after the room cards in the deck
		cardNum += numSuspects + numRooms
	}

	// remove the card from the deck
	deck = slices.DeleteFunc(deck, func(c int) bool {
		return c == cardNum
	})

	return deck
}

func (g *GameLogicManager) setupPlayerLocations(playerIDs []string) {
	g.session.broadcastMessage("Setting up player locations...")

	// set initial locations for all players
	for _, playerID := range playerIDs {
		location := playerLocation{
			// randomly select a room
			isHall: false,
			//nolint:gosec // rand.IntN is used for selecting random rooms, not for security-sensitive purposes.
			location: rand.IntN(numRooms) + 1,
		}
		g.locations[playerID] = &location
	}

	for _, playerID := range playerIDs {
		g.session.broadcastMessage(fmt.Sprintf(playerLocationFmt, playerID, g.locations[playerID].isHall, g.locations[playerID].location))
	}
}
