package session

import (
	"fmt"
	"math/rand/v2"
	"maps"
	"slices"

	sessionv1 "github.com/TeamHermes-jhu/clueless/backend/internal/gen/session/v1"
	suggestionv1 "github.com/TeamHermes-jhu/clueless/backend/internal/gen/suggestion/v1"
)

const (
	// text formats for logging
	suggestFmt = "player %s has suggested: %s with the %s in the %s"
	accuseFmt  = "player %s has made an accusation: %s with the %s in the %s"
	moveFmt    = "player %s has moved to %s"

	// number of each type of card in the game
	numSuspects = 6
	numRooms    = 9
	numWeapons  = 6

	// card type numbers
	cardSuspect = 1
	cardRoom    = 2
	cardWeapon  = 3

	// number of halls in the game
	numHalls = 12

	// debug text formats
	caseFileFmt = "Spoiler alert! case file: suspect %d, room %d, weapon %d"
	playerHandFmt = "player %s hand: suspects %v, rooms %v, weapons %v"
	playerLocationFmt = "player %s location: isHall %t, location %d"
)

type playerLocation struct {
	// the location of a player in the game
	// can be a room or a hall
	isHall bool
	location int
}

type CaseFile struct {
	// the case file contains the suspect, room, and weapon that are the solution to the game
	// the cardsv1 stuff generated by protobuf is a MESSAGE, not the struct itself, so we 
	// just store the int values of the cards in the case file
	suspectCard int
	roomCard    int
	weaponCard  int
}

type PlayerHand struct {
	// store the cards in the player's hand
	// can have multiple cards of the same type, so each is an array
	suspectCards []int
	roomCards    []int
	weaponCards  []int
}

type GameLogicManager struct {

	// needs to be associated with a session (contains turn order, players, turnIdx)
	session *Session

	// needs to maintain a case file (suspect, room, weapon)
	caseFile CaseFile

	// needs to maintain all the players' hands
	hands map[string]*PlayerHand

	// needs to maintain the location of all the players
	locations map[string]*playerLocation

}

func (s *Session) startGame() {
	s.logger.Info("Starting game", "players", len(s.players))
	s.started = true

	s.broadcastMessage("game is starting")

	r := rand.Perm(len(s.players))

	s.turnOrder = make([]string, len(s.joinOrder))
	for i, v := range r {
		s.turnOrder[v] = s.joinOrder[i]
	}

	g := GameLogicManager{
		session: s,
		caseFile: CaseFile{},
		hands: make(map[string]*PlayerHand),
		locations: make(map[string]*playerLocation),
	}

	playerIds := slices.Collect(maps.Keys(s.players))

	g.setupGame(playerIds)
}

func (s *Session) move(move *sessionv1.Move) {
	// TODO: validate its a good move
	to := move.GetRoom().String()

	if move.WhichMoveTo() == sessionv1.Move_Hall_case {
		to = move.GetRoom().String()
	}

	s.broadcastMessage(fmt.Sprintf(moveFmt, move.GetPlayerId(), to))
}

